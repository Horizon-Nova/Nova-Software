-- 工具表多一欄 settings：這支工具的設定畫面型別全名；vw_shell 跟著多帶出這一欄
ALTER TABLE dbo.tool_management ADD COLUMN IF NOT EXISTS settings text;
COMMENT ON COLUMN dbo.tool_management.settings IS '組件裡設定畫面的型別全名，例如 InSpecTool.Setup；沒有就是這支工具沒有設定';

CREATE OR REPLACE VIEW dbo.vw_shell AS
SELECT 'tool'::text AS type,
       t.id,
       t.tool_no,
       t.name,
       t.icon,
       t.cat,
       t.vendor,
       t.version,
       t.installed_version,
       t.state,
       t.required,
       t.pinned,
       t.badge,
       t.auto_update,
       t.audience,
       t.size,
       t.updated,
       t.description,
       t.guide,
       t.seats,
       t.capabilities,
       t.permissions,
       t.changelog,
       t.usage,
       t.entry,
       t.class,
       t.home,
       t.source,
       NULL::text AS host,
       NULL::text AS os,
       NULL::text AS ip,
       NULL::text AS client,
       NULL::text AS build,
       NULL::text AS sync_at,
       NULL::text AS dept,
       '[]'::jsonb AS roles,
       NULL::timestamptz AS used_at,
       t.settings
  FROM dbo.tool_management AS t
 WHERE t.type = 'tool'
UNION ALL
SELECT d.type,
       d.id,
       NULL,
       d.name,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       '{}'::jsonb,
       '[]'::jsonb,
       '[]'::jsonb,
       '[]'::jsonb,
       '[]'::jsonb,
       NULL,
       NULL,
       NULL,
       NULL,
       d.host,
       d.os,
       d.ip,
       d.client,
       d.build,
       d.sync_at,
       d.dept,
       d.roles,
       NULL::timestamptz,
       NULL::text
  FROM dbo.device_management AS d
UNION ALL
SELECT 'search'::text,
       s.id,
       NULL,
       s.term,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       '{}'::jsonb,
       '[]'::jsonb,
       '[]'::jsonb,
       '[]'::jsonb,
       '[]'::jsonb,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       NULL,
       '[]'::jsonb,
       s.used_at,
       NULL::text
  FROM dbo.search_management AS s
 ORDER BY type, used_at DESC NULLS LAST, id;
