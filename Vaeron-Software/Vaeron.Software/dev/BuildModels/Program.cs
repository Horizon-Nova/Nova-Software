using System.Reflection;
using System.Text.RegularExpressions;
using Microsoft.EntityFrameworkCore.Design;
using Microsoft.EntityFrameworkCore.Scaffolding;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Npgsql.EntityFrameworkCore.PostgreSQL.Design.Internal;

// 產生的檔案開頭掛的橫幅。Save 每次都整份覆寫，所以直接前置，不必檢查有沒有掛過。
const string Warning = """
// ╔════════════════════════════════════════════════════════════════════════╗
// ║                     嚴重警告 / CRITICAL WARNING                        ║
// ╠════════════════════════════════════════════════════════════════════════╣
// ║  此檔案為系統自動生成，禁止手動修改！                                    ║
// ║  This file is AUTO-GENERATED by the system. DO NOT MODIFY manually!    ║
// ║                                                                          ║
// ║  任何手動修改將在下次重新生成時被覆蓋且遺失！                            ║
// ║  Any manual changes will be OVERWRITTEN and LOST on next generation!   ║
// ║                                                                          ║
// ║  如需修改，請調整資料庫結構後重新執行 BuildModels 工具                   ║
// ║  To make changes, modify the database schema and re-run BuildModels     ║
// ╚════════════════════════════════════════════════════════════════════════╝

""";

// 摘要標記的樣式：開頭標記、一行或多行內容、結尾標記，各自一行
const string SummaryPattern = @"([ \t]*)/// <summary>\r?\n(?:[ \t]*/// (?<line>.*)\r?\n)+?[ \t]*/// </summary>";

// 工作區根由 csproj 在建置時寫進組件中繼資料，執行時不必往上找。
var metadata = Assembly.GetExecutingAssembly()
    .GetCustomAttributes<AssemblyMetadataAttribute>()
    .ToDictionary(attribute => attribute.Key, attribute => attribute.Value!);

// 目標清單在這裡；連線字串讀平台開發用的那一份，不另外再存一份密碼
var configuration = new ConfigurationBuilder()
    .SetBasePath(AppContext.BaseDirectory)
    .AddJsonFile("appsettings.json", optional: false)
    .AddJsonFile(Path.Combine(metadata["WorkspaceRoot"], "src", "HelixStudio", "appsettings.json"), optional: false)
    .Build();

var services = new ServiceCollection();
services.AddEntityFrameworkDesignTimeServices();
new NpgsqlDesignTimeServices().ConfigureDesignTimeServices(services);
using var provider = services.BuildServiceProvider();
var scaffolder = provider.GetRequiredService<IReverseEngineerScaffolder>();

// 一個目標一份模型：哪一個資料庫、哪幾張表或檢視、落在哪一個專案底下；同一個資料庫可以給好幾個專案各生一份。
foreach (var target in configuration.GetSection("ScaffoldSettings:Targets").GetChildren())
{
    var database = target["Database"]!;
    var tables = target.GetSection("Tables").GetChildren().Select(table => table.Value!).ToArray();
    var outputDirectory = Path.GetFullPath(Path.Combine(metadata["WorkspaceRoot"], target["Output"]!));

    Console.WriteLine($"{database}：{string.Join("、", tables)} → {outputDirectory}");

    var model = scaffolder.ScaffoldModel(
        connectionString: configuration.GetConnectionString(database)!,
        databaseOptions: new DatabaseModelFactoryOptions(tables, []),
        modelOptions: new ModelReverseEngineerOptions { UseDatabaseNames = true },
        codeOptions: new ModelCodeGenerationOptions
        {
            ContextName = $"{database}DbContext",
            ContextDir = outputDirectory,
            ModelNamespace = $"Models.{database}",
            ContextNamespace = $"Models.{database}",
            SuppressOnConfiguring = true,
            SuppressConnectionStringWarning = true,
            UseDataAnnotations = true,
            UseNullableReferenceTypes = true,
        });

    var saved = scaffolder.Save(model, outputDirectory, overwriteFiles: true);

    foreach (var file in saved.AdditionalFiles.Prepend(saved.ContextFile))
    {
        File.WriteAllText(file, Warning + OneLine(File.ReadAllText(file)));
        Console.WriteLine($"  {file}");
    }
}

// 摘要標記一行。產生器把它拆成三行寫出來，這裡在落檔前收回一行。
static string OneLine(string text) =>
    Regex.Replace(
        text,
        SummaryPattern,
        one => one.Groups[1].Value
             + "/// <summary>"
             + string.Concat(one.Groups["line"].Captures.Select(each => each.Value.Trim()))
             + "</summary>");
