using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Vaeron.Generators;

// 自動註冊：掃標記屬性,非掃介面。
// ForAttributeWithMetadataName 專為此設計,可增量;掃介面或基底型別無法增量化。
[Generator]
public sealed class RegistrationGenerator : IIncrementalGenerator
{
    private const string AttributeName = "Vaeron.Kernel.Composition.RegisterAttribute";

    private readonly struct Registration
    {
        public Registration(string implementation, string contract, string lifetime)
        {
            Implementation = implementation;
            Contract = contract;
            Lifetime = lifetime;
        }

        public string Implementation { get; }
        public string Contract { get; }
        public string Lifetime { get; }
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName,
            predicate: static (_, _) => true,
            transform: static (ctx, _) =>
            {
                var type = (INamedTypeSymbol)ctx.TargetSymbol;
                var attribute = ctx.Attributes[0];

                var lifetime = attribute.ConstructorArguments.Length > 0
                    ? attribute.ConstructorArguments[0].Value?.ToString() ?? "0"
                    : "0";

                var contract = type.AllInterfaces.Length > 0
                    ? type.AllInterfaces[0].ToDisplayString()
                    : type.ToDisplayString();

                return new Registration(
                    type.ToDisplayString(),
                    contract,
                    LifetimeName(lifetime));
            });

        context.RegisterSourceOutput(candidates.Collect(), Emit);
    }

    // 列舉值以整數傳遞,轉為 ServiceCollection 的方法名
    private static string LifetimeName(string raw) => raw switch
    {
        "1" => "Transient",
        "2" => "Scoped",
        _ => "Singleton"
    };

    private static void Emit(SourceProductionContext context, ImmutableArray<Registration> items)
    {
        if (items.IsDefaultOrEmpty)
        {
            return;
        }

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine();
        builder.AppendLine("namespace Vaeron.Generated;");
        builder.AppendLine();
        builder.AppendLine("internal static class GeneratedRegistration");
        builder.AppendLine("{");
        builder.AppendLine("    public static IServiceCollection AddGenerated(this IServiceCollection services)");
        builder.AppendLine("    {");

        foreach (var item in items.Select(i => (i.Implementation, i.Contract, i.Lifetime)).Distinct())
        {
            builder.AppendLine(
                $"        services.Add{item.Lifetime}<{item.Contract}, {item.Implementation}>();");
        }

        builder.AppendLine("        return services;");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        context.AddSource("GeneratedRegistration.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
    }
}
